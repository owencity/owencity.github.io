CREATE TABLE IF NOT EXISTS news_item (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  source_id VARCHAR(1000) NOT NULL UNIQUE,
  title VARCHAR(1500) NOT NULL,
  url VARCHAR(4000) NOT NULL,
  description TEXT NOT NULL,
  published_at TIMESTAMP WITH TIME ZONE,
  collected_at TIMESTAMP WITH TIME ZONE NOT NULL,
  topic VARCHAR(80) NOT NULL,
  feedback VARCHAR(30) NOT NULL DEFAULT 'NONE',
  CONSTRAINT news_feedback_valid CHECK (feedback IN ('NONE','INTERESTED','NOT_INTERESTED','KNOWN','LATER','READ'))
);
CREATE INDEX IF NOT EXISTS news_published_idx ON news_item(published_at DESC);
CREATE INDEX IF NOT EXISTS news_feedback_idx ON news_item(feedback);
CREATE TABLE IF NOT EXISTS news_feedback_event (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  news_id BIGINT NOT NULL REFERENCES news_item(id),
  feedback VARCHAR(30) NOT NULL,
  created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT feedback_event_valid CHECK (feedback IN ('NONE','INTERESTED','NOT_INTERESTED','KNOWN','LATER','READ'))
);
CREATE INDEX IF NOT EXISTS feedback_event_news_idx ON news_feedback_event(news_id, created_at);
CREATE TABLE IF NOT EXISTS feed_state (
  id INTEGER PRIMARY KEY,
  last_collected_at TIMESTAMP WITH TIME ZONE,
  error VARCHAR(250)
);
INSERT INTO feed_state(id) SELECT 1 WHERE NOT EXISTS (SELECT 1 FROM feed_state WHERE id=1);
CREATE TABLE IF NOT EXISTS digest_delivery (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  digest_date DATE NOT NULL,
  channel VARCHAR(30) NOT NULL,
  status VARCHAR(30) NOT NULL,
  created_at TIMESTAMP WITH TIME ZONE NOT NULL,
  updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
  detail VARCHAR(250),
  UNIQUE(digest_date, channel)
);
